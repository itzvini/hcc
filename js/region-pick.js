function pill(link, when) { return { ...link, when }; }
function global(id, rest) {
  return { id, kind: 'global', name: BRAND[id].name, logo: BRAND[id].logo, diamond: !!BRAND[id].diamond, open: id, ...rest };
}

// A row's name is a button that opens that option's dossier above it, so the two sections
// have to agree on which card that is. The cash-out section has one card per company; the
// funding section has two, "Card, on this site" and one "An exchange" card covering all
// three, so every exchange row there points at that one. Getting this wrong is a button
// that silently does nothing, which is why the mapping lives here and not in the markup.
const CARD_FOR = { funding: { tx: 'tx', cb: 'cex', kr: 'cex', bn: 'cex' } };
function cardFor(mode, id) {
  const map = CARD_FOR[mode];
  return map ? map[id] || null : id;
}
function binanceSite(c) {
  const site = BINANCE.sites[c] || BINANCE.sites.default;
  const when = site.whenKey ? t(site.whenKey) : undefined;
  return pill({ href: `https://${site.host}`, pre: site.host.slice(0, site.host.length - site.dom.length), dom: site.dom }, when);
}

// Binance answers half the question in public, and the page says which half.
//
// COUNTRIES[c].bn comes from Binance's own signup country list, where the United States and
// its territories, Cuba, Iran and North Korea are simply absent. But that list is evidence
// about a DROPDOWN, not about service: Canada and the Netherlands are still on it years
// after Binance announced it was leaving both. So a country on the list gets "Limited" and
// wording that claims no more than the list can carry, BINANCE.left overrides it with the
// announced exits, and the bank rail is never asserted at all — Binance publishes it
// nowhere, every fiat endpoint 404s, and the one fiat menu it serves mixes bank rails with
// person-to-person currencies. Curated `bn.st` wins wherever someone confirmed a real rail.
function binanceRow(c, s, mode, V) {
  const b = (CURATED[c] || {}).bn || {};
  const site = BINANCE.sites[c] || BINANCE.sites.default;
  const no = () => global('bn', { status: 'no', why: fmt('gm.geo.bn.no', V), links: [] });

  if (b.st === 'no') return no();
  // The United States is off binance.com entirely and served by a different company, so it
  // never falls through to the signup flag, which would only say "absent".
  if (c === 'US') {
    if (s && BINANCE.usNotServed.includes(s)) return no();
    if (s && BINANCE.usCryptoOnly.includes(s)) return global('bn', { status: 'ltd', why: fmt('gm.geo.bn.usCrypto', V), links: [binanceSite(c)] });
    return global('bn', { status: 'ltd', why: fmt('gm.geo.bn.us', V), links: [binanceSite(c)] });
  }
  if (BINANCE.restricted.includes(c) && !BINANCE.sites[c]) return no();
  // An announced exit beats the signup list, which still carries both of them.
  if (BINANCE.left[c]) return global('bn', { status: 'no', why: fmt('gm.geo.bn.left', { ...V, date: BINANCE.left[c] }), links: [] });
  // The MiCA suspension beats it too, and for the same reason: the signup list still
  // carries all thirty EEA countries months after Binance switched them off.
  if (BINANCE.mica.includes(c)) return global('bn', { status: 'no', why: fmt('gm.geo.bn.mica', { ...V, date: BINANCE.micaDate }), links: [] });
  if (BINANCE.blocked[c]) return global('bn', { status: 'no', why: fmt('gm.geo.bn.blocked', { ...V, date: BINANCE.blocked[c] }), links: [] });
  if (BINANCE.exiting[c]) return global('bn', { status: 'ltd', why: fmt('gm.geo.bn.exiting', { ...V, date: BINANCE.exiting[c], site: site.dom }), links: [binanceSite(c)] });
  if (BINANCE.frozen[c]) return global('bn', { status: 'ltd', why: fmt('gm.geo.bn.frozen', { ...V, date: BINANCE.frozen[c] }), links: [binanceSite(c)] });
  if (b.st === 'p2p') return global('bn', { status: 'ltd', why: fmt('gm.geo.bn.p2p', V), links: [binanceSite(c)] });
  if (b.st === 'ok') {
    const rails = b.rails && b.rails.length ? railNames(b.rails) : null;
    const key = mode === 'funding' ? (rails ? 'gm.geo.bn.buy' : 'gm.geo.bn.okNoRails') : (rails ? 'gm.geo.bn.ok' : 'gm.geo.bn.okNoRails');
    return global('bn', { status: 'ok', why: fmt(key, { ...V, site: site.dom, rails }), links: [binanceSite(c)] });
  }
  const signup = COUNTRIES[c].bn;
  if (signup === 0) return no();
  if (signup === 1) {
    const key = mode === 'funding' ? 'gm.geo.bn.acctBuy' : 'gm.geo.bn.acct';
    return global('bn', { status: 'ltd', why: fmt(key, { ...V, site: site.dom }), links: [binanceSite(c)] });
  }
  return global('bn', { status: 'unk', why: fmt('gm.geo.bn.unk', V), links: [binanceSite(c)] });
}

function krakenRow(c, s, mode, V) {
  const cu = (CURATED[c] || {}).kr || {};
  const served = cu.ok !== 0 && !KRAKEN.notServed.includes(c) && !(c === 'US' && s && KRAKEN.usNotServed.includes(s));
  const fiat = cu.fiat || (KRAKEN.fiat[V.cur] ? V.cur : null);
  const rails = cu.rails || (fiat && KRAKEN.fiat[fiat]) || [];
  if (!served) return global('kr', { status: 'no', why: fmt('gm.geo.kr.no', V), links: [] });
  if (!fiat) return global('kr', { status: 'ltd', why: fmt(mode === 'funding' ? 'gm.geo.kr.buyNoFiat' : 'gm.geo.kr.noFiat', V), links: [pill(LINKS.kr)] });
  const key = mode === 'funding' ? (rails.length ? 'gm.geo.cex.buy' : 'gm.geo.cex.buyNoRails') : (rails.length ? 'gm.geo.kr.ok' : 'gm.geo.cb.okNoRails');
  return global('kr', { status: 'ok', why: fmt(key, { ...V, rails: railNames(rails) }), links: [pill(LINKS.kr)] });
}

// Coinbase retired its public country feed, so there is no generated list to lean on and
// every state here comes from the curated file. Four answers, not two: it opens accounts
// in far more places than it pays a bank in, and the page must not blur the two.
function coinbaseRow(c, mode, V) {
  const cb = (CURATED[c] || {}).cb;
  if (!cb) return global('cb', { status: 'unk', why: fmt('gm.geo.cb.unk', V), links: [pill(LINKS.cb)] });
  if (cb.acct === 0) return global('cb', { status: 'no', why: fmt('gm.geo.cb.no', V), links: [] });
  const flag = mode === 'funding' ? (cb.buy ?? cb.cash) : cb.cash;
  const rails = cb.rails || [];
  if (flag === 1) {
    const key = mode === 'funding' ? (rails.length ? 'gm.geo.cex.buy' : 'gm.geo.cex.buyNoRails') : (rails.length ? 'gm.geo.cb.ok' : 'gm.geo.cb.okNoRails');
    return global('cb', { status: 'ok', why: fmt(key, { ...V, rails: railNames(rails) }), links: [pill(LINKS.cb)] });
  }
  if (flag === 0) return global('cb', { status: 'ltd', why: fmt('gm.geo.cb.convert', V), links: [pill(LINKS.cb)] });
  return global('cb', { status: 'ltd', why: fmt(mode === 'funding' ? 'gm.geo.cb.buyAcctOnly' : 'gm.geo.cb.acctOnly', V), links: [pill(LINKS.cb)] });
}

function metamaskRow(c, s, V) {
  const d = COUNTRIES[c];
  const st = c === 'US' && s ? US_STATES[s] : null;
  const mm = st ? st.mm : d.mm;   // [buy, sell]
  // A state answers for itself where MetaMask gives it its own list.
  const rails = (CURATED[c] || {}).mm?.rails || (st && st.mmRails) || d.mmRails || [];
  if (!mm[1]) return global('mm', { status: 'no', why: fmt(mm[0] ? 'gm.geo.mm.nosell' : 'gm.geo.mm.none', V), links: [] });
  const why = rails.length ? fmt('gm.geo.mm.ok', { ...V, rails: railNames(rails) }) : fmt('gm.geo.mm.okNoRails', V);
  return global('mm', { status: 'ok', why, links: [pill(LINKS.mm, t('gm.paid.go.mm.note'))] });
}

// Three states, because Transak's own feeds have three answers. A country its currency
// list covers is confirmed; one its document list blocks is a no; everything else is
// unconfirmed, and saying so beats telling someone in India the card doesn't work.
function transakRow(c, s, V) {
  const tx = COUNTRIES[c].tx;
  const blocked = c === 'US' && s && TRANSAK.usNotServed.includes(s);
  const row = { id: 'tx', kind: 'card', name: t('gm.get.card.name'), open: 'tx' };
  if (blocked || (tx && !tx.ok)) return { ...row, status: 'no', why: fmt('gm.geo.tx.no', V), links: [] };
  if (!tx) return { ...row, status: 'unk', why: fmt('gm.geo.tx.unk', V), links: [pill(LINKS.tx, t('gm.get.go.here'))] };
  const methods = tx.pay && tx.pay.length ? railNames(tx.pay) : null;
  return {
    ...row, status: 'ok',
    why: fmt(methods ? 'gm.geo.tx.ok' : 'gm.geo.tx.okNoMethods', { ...V, methods }),
    links: [pill(LINKS.tx, t('gm.get.go.here'))],
  };
}

function localRows(c, s, mode, V) {
  return ((CURATED[c] || {}).loc || []).flatMap(l => {
    if (mode === 'cashout' && l.sell === 0) return [];
    if (mode === 'funding' && l.buy === 0) return [];
    if (s && (l.notIn || []).includes(s)) return [];   // a venue its own state list rules out
    const link = pill({ href: `https://${l.d}`, pre: '', dom: l.d });
    const base = { id: `loc:${l.d}`, kind: 'local', name: l.n, reg: l.reg, links: [link] };
    if (mode === 'funding' && l.wd === 0) return [{ ...base, status: 'no', why: fmt('gm.geo.loc.noWd', V), links: [] }];
    const rails = l.rails && l.rails.length ? railNames(l.rails) : null;
    const key = mode === 'cashout' ? (rails ? 'gm.geo.loc.sell' : 'gm.geo.loc.sellNoRails') : (rails ? 'gm.geo.loc.buy' : 'gm.geo.loc.buyNoRails');
    return [{ ...base, status: 'ok', why: fmt(key, { ...V, rails }) }];
  });
}

// The cheapest route that actually pays (or takes) local money: published trading fees
// rank Binance under Kraken under Coinbase, and a vetted local venue closes the list.
function cheapest(rows) {
  for (const id of ['bn', 'kr', 'cb']) {
    const r = rows.find(x => x.id === id && x.status === 'ok');
    if (r) return r.name;
  }
  const loc = rows.find(x => x.kind === 'local' && x.status === 'ok');
  return loc ? loc.name : null;
}

function evaluate(mode, c, s) {
  const d = COUNTRIES[c];
  const V = { place: placeName(c, s), currency: currencyName(d.cur), cur: d.cur };
  const rows = [];
  const point = () => rows.forEach(r => { if (r.kind !== 'local') r.open = cardFor(mode, r.id); });
  // Under comprehensive sanctions the verdict is not "the cheapest of what's left", and
  // the fallback line about selling into dollars would be advice we can't stand behind.
  if ((CURATED[c] || {}).legal === 'sanctioned') {
    if (mode === 'cashout') rows.push(metamaskRow(c, s, V), coinbaseRow(c, 'cashout', V), krakenRow(c, s, 'cashout', V), binanceRow(c, s, 'cashout', V));
    else rows.push(transakRow(c, s, V), coinbaseRow(c, 'funding', V), krakenRow(c, s, 'funding', V), binanceRow(c, s, 'funding', V));
    point();
    return { rows, verdict: fmt('gm.geo.v.sanctioned', V) };
  }
  if (mode === 'cashout') {
    rows.push(metamaskRow(c, s, V), coinbaseRow(c, 'cashout', V), krakenRow(c, s, 'cashout', V), binanceRow(c, s, 'cashout', V), ...localRows(c, s, 'cashout', V));
    const first = rows[0].status === 'ok';
    const cheap = cheapest(rows);
    const key = first ? (cheap ? 'gm.geo.v.cash.mm' : 'gm.geo.v.cash.mmOnly') : (cheap ? 'gm.geo.v.cash.noMm' : 'gm.geo.v.cash.none');
    point();
    return { rows, verdict: fmt(key, { ...V, cheap }) };
  }
  rows.push(transakRow(c, s, V), coinbaseRow(c, 'funding', V), krakenRow(c, s, 'funding', V), binanceRow(c, s, 'funding', V), ...localRows(c, s, 'funding', V));
  const first = rows[0].status === 'ok';
  const cheap = cheapest(rows);
  const key = first ? (cheap ? 'gm.geo.v.fund.tx' : 'gm.geo.v.fund.txOnly') : (cheap ? 'gm.geo.v.fund.noTx' : 'gm.geo.v.fund.none');
  point();
  return { rows, verdict: fmt(key, { ...V, cheap }) };
}

// ---------- markup ----------

function pillHtml(l) {
  const ext = !l.internal;
  return `<a class="gm-go-link" href="${esc(l.href)}"${ext ? ' target="_blank" rel="noopener noreferrer"' : ''}>`
    + `<span class="gm-go-dom">${esc(l.pre || '')}<b>${esc(l.dom)}</b>${esc(l.path || '')}</span>`
    + (l.when ? ` <em class="gm-go-when">${esc(l.when)}</em>` : '')
    + ` <span class="gm-go-arrow" aria-hidden="true">${ext ? '↗' : '→'}</span></a>`;
}

function rowHtml(r, i) {
  let ico;
  if (r.kind === 'global') ico = `<span class="gm-geo-ico${r.diamond ? ' is-diamond' : ''}"><img src="${esc(r.logo)}" alt="" width="22" height="22"></span>`;
  else ico = `<span class="gm-geo-ico is-plain" aria-hidden="true">${r.kind === 'card' ? CARD_SVG : BANK_SVG}</span>`;
  const name = r.open
    ? `<button type="button" class="gm-geo-name" data-geo-open="${esc(r.open)}" title="${esc(t('gm.geo.open'))}">${esc(r.name)}</button>`
    : `<b class="gm-geo-name">${esc(r.name)}</b>`;
  const tag = r.kind === 'local' ? `<span class="gm-geo-tag">${esc(t('gm.geo.local'))}</span>` : '';
  const reg = r.reg ? `<span class="gm-geo-reg">${esc(r.reg)}</span>` : '';
  return `<li class="gm-geo-row is-${r.status}" style="--i:${i}">${ico}`
    + `<div class="gm-geo-main"><div class="gm-geo-hd">${name}<span class="gm-geo-st is-${r.status}">${esc(t(`gm.geo.st.${r.status}`))}</span>${tag}${reg}</div>`
    + `<p class="gm-geo-why">${r.why}</p></div>`
    + `<div class="gm-geo-links">${r.links.map(pillHtml).join('')}</div></li>`;
}

function emptyHtml(mode) {
  const chips = COMMON.filter(c => COUNTRIES[c])
    .map(c => `<button type="button" class="gm-geo-chip" data-geo-set="${c}">${esc(countryName(c, uiLang()))}</button>`).join('');
  return `<div class="gm-geo-empty"><p>${esc(t(`gm.geo.empty.${mode}`))}</p>`
    + (chips ? `<div class="gm-geo-common"><span class="gm-geo-common-l">${esc(t('gm.geo.common'))}</span>${chips}</div>` : '')
    + '</div>';
}

function resultHtml(mode, c, s) {
  const cu = CURATED[c] || {};
  const place = placeName(c, s);
  const ev = evaluate(mode, c, s);
  let alert = '';
  if (cu.legal === 'sanctioned') alert = `<p class="gm-geo-alert">${fmt('gm.geo.sanctioned', { place })}</p>`;
  else if (cu.legal === 'restricted' && cu.legalNote) alert = `<p class="gm-geo-alert is-soft">${esc(t(cu.legalNote))}</p>`;
  const noteKeys = [...(cu.notes || []), ...((mode === 'cashout' ? cu.notesCash : cu.notesFund) || [])];
  // The default note for a country nobody has written up. Two versions, because pointing a
  // reader at MetaMask's sell page is good advice only if MetaMask might sell there. When
  // MetaMask's own list says no AND MoonPay's independently agrees — MoonPay is one of the
  // companies behind that page, and its coverage is cross-checked at build time — sending
  // them off to confirm a refusal wastes their time.
  const d = COUNTRIES[c];
  const deadEnd = !d.mm[1] && d.mp && !d.mp[1];
  const notes = noteKeys.length
    ? `<ul>${noteKeys.map(k => `<li>${esc(t(`gm.geo.note.${k}`))}</li>`).join('')}</ul>`
    : `<p>${fmt(deadEnd ? 'gm.geo.notes.noneDead' : 'gm.geo.notes.none', { place })}</p>`;
  return `<div class="gm-geo-res">`
    + `<div class="gm-geo-verdict"><span class="gm-pick-tag">${fmt('gm.geo.in', { place })}</span><p>${ev.verdict}</p></div>`
    + alert
    + `<ul class="gm-geo-rows" role="list">${ev.rows.map(rowHtml).join('')}</ul>`
    + `<div class="gm-geo-notes"><b>${fmt('gm.geo.notes.h', { place })}</b>${notes}</div>`
    // One date when both halves were checked the same day, which is the usual case and
    // reads as a fact rather than as bookkeeping.
    + `<p class="gm-geo-fine">${CHECKED.date === LOCALS_CHECKED
        ? fmt('gm.geo.fine1', { date: fmtDate(CHECKED.date) })
        : fmt('gm.geo.fine', { date: fmtDate(CHECKED.date), date2: fmtDate(LOCALS_CHECKED) })}</p>`
    + '</div>';
}

// ---------- the selects ----------

function fillCountrySelect(sel) {
  const codes = Object.keys(COUNTRIES).map(c => [c, countryName(c, uiLang())]).sort((a, b) => a[1].localeCompare(b[1], uiLang()));
  sel.replaceChildren(
    new Option(t('gm.geo.pick'), '', true, !pick.c),
    ...codes.map(([c, n]) => new Option(n, c, false, c === pick.c)),
  );
  sel.value = pick.c || '';
}
function fillStateSelect(sel) {
  const states = Object.entries(US_STATES).sort((a, b) => a[1].n.localeCompare(b[1].n, 'en'));
  sel.replaceChildren(
    new Option(t('gm.geo.pickState'), '', true, !pick.s),
    ...states.map(([code, st]) => new Option(st.n, code, false, code === pick.s)),
  );
  sel.value = pick.s || '';
}

function renderRoot(root) {
  const mode = root.dataset.geo;
  const country = root.querySelector('[data-geo-country]');
  const state = root.querySelector('[data-geo-state]');
  const stateWrap = root.querySelector('[data-geo-statewrap]');
  const hint = root.querySelector('[data-geo-hint]');
  const out = root.querySelector('[data-geo-out]');
  if (country && country.value !== (pick.c || '')) country.value = pick.c || '';
  if (state && state.value !== (pick.s || '')) state.value = pick.s || '';
  if (stateWrap) stateWrap.hidden = pick.c !== 'US';
  if (hint) {
    const show = !!hintRegion && hintRegion !== pick.c && !pick.c;
    hint.hidden = !show;
    if (show) { hint.textContent = fmt('gm.geo.hint', { country: countryName(hintRegion) }); hint.dataset.geoSet = hintRegion; }
  }
  if (!out) return;
  if (!pick.c) { out.innerHTML = emptyHtml(mode); return; }
  if (pick.c === 'US' && !pick.s) { out.innerHTML = `<div class="gm-geo-empty"><p>${esc(t('gm.geo.needState'))}</p></div>`; return; }
  out.innerHTML = resultHtml(mode, pick.c, pick.s);
  // Glossary links for the prose we just wrote. Fetched, never imported: a decoration
  // must not be able to take the picker down with it.
  import('./glossary-link.js').then(m => m.linkGlossaryTerms(out)).catch(() => {});
}

function renderAll() { roots.forEach(renderRoot); }

function setCountry(c) {
  pick = COUNTRIES[c] ? { c, s: null } : { c: null, s: null };
  savePick();
  renderAll();
}
function setState(s) {
  pick.s = pick.c === 'US' && US_STATES[s] ? s : null;
  savePick();
  renderAll();
}

// Expand the matching option card above and bring it into view. Chromium ignores
// scroll-margin when a <details> is the scrollIntoView target, so the scroll is by hand.
function openCard(root, key) {
  const section = root.closest('.gm-paid');
  const card = section && section.querySelector(`.gm-opt[data-opt="${key}"]`);
  if (!card) return;
  card.open = true;
  const margin = parseFloat(getComputedStyle(document.documentElement).getPropertyValue('--nav-clear')) || 80;
  const smooth = !matchMedia('(prefers-reduced-motion: reduce)').matches;
  window.scrollTo({ top: card.getBoundingClientRect().top + window.scrollY - margin - 8, behavior: smooth ? 'smooth' : 'instant' });
  card.querySelector('summary')?.focus({ preventScroll: true });
}

// ---------- public API ----------

export function initRegionPick() {
  roots = [...document.querySelectorAll('[data-geo]')];
  if (!roots.length) return;
  hintRegion = browserRegion();
  roots.forEach(root => {
    const country = root.querySelector('[data-geo-country]');
    const state = root.querySelector('[data-geo-state]');
    if (country) { fillCountrySelect(country); country.addEventListener('change', () => setCountry(country.value)); }
    if (state) { fillStateSelect(state); state.addEventListener('change', () => setState(state.value)); }
    // The controls ship hidden so a reader whose JS never arrives gets the static facts
    // instead of two empty dropdowns. They appear only once they can actually answer.
    const bar = root.querySelector('[data-geo-bar]');
    if (bar) bar.hidden = false;
    // Delegated: the chips, the hint and the card-openers are re-rendered on every change.
    root.addEventListener('click', e => {
      const set = e.target.closest?.('[data-geo-set]');
      if (set && root.contains(set)) { setCountry(set.dataset.geoSet); root.querySelector('[data-geo-country]')?.focus(); return; }
      const open = e.target.closest?.('[data-geo-open]');
      if (open && root.contains(open)) openCard(root, open.dataset.geoOpen);
    });
  });
  renderAll();
}

// After translations load and on every language switch: country names, labels and the
// answer all change language, and the selects have to be rebuilt to re-sort.
export function rerenderRegionPick() {
  roots.forEach(root => {
    const country = root.querySelector('[data-geo-country]');
    const state = root.querySelector('[data-geo-state]');
    if (country) fillCountrySelect(country);
    if (state) fillStateSelect(state);
  });
  renderAll();
}

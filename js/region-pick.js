function loadPick() {
  try {
    const p = JSON.parse(localStorage.getItem(KEY) || 'null');
    if (p && COUNTRIES[p.c]) return { c: p.c, s: p.c === 'US' && p.s && US_STATES[p.s] ? p.s : null };
  } catch {}
  return { c: null, s: null };
}
function savePick() {
  try { localStorage.setItem(KEY, JSON.stringify(pick)); } catch {}
}

// A region a member's browser already declares (pt-BR, tr-TR, es-MX). A lone en-US is
// the factory default on half the world's browsers, so it says nothing and is skipped.
function browserRegion() {
  const tags = (navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language]).filter(Boolean);
  if (tags.length === 1 && /^en-US$/i.test(tags[0])) return null;
  for (const tag of tags) {
    try {
      const r = new Intl.Locale(tag).region;
      if (r && COUNTRIES[r]) return r;
    } catch {}
  }
  return null;
}

// ---------- text helpers ----------

function esc(s) {
  return String(s ?? '').replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
}
// Fill {token} placeholders. Values are escaped here, so the result is safe as HTML.
function fmt(key, vars = {}) {
  return String(t(key)).replace(/\{(\w+)\}/g, (m, k) => (k in vars ? esc(vars[k]) : m));
}
// The language to format country names, currencies, lists and dates in — which is the
// language this block's COPY resolved to, not the one the site is set to. The whole
// cash-out family is English-only and rides the fallback, so a Portuguese reader was
// getting English sentences with "Dólar americano" and "e" dropped into them. Ask i18n
// whether the active dictionary really has these strings; the day they're translated,
// this starts returning the reader's language on its own.
function lang() {
  return hasTranslation('gm.geo.country') ? uiLang() : 'en';
}
// The reader's actual language, for the two places where finding your own country beats
// matching the prose: the option labels and the order they're sorted in. A label is not a
// sentence, so nothing reads as half-translated there.
function uiLang() { return getCurrentLang() || 'en'; }
function displayNames(type, forLang) {
  try { return new Intl.DisplayNames([forLang || lang()], { type, fallback: 'code' }); } catch { return null; }
}
// English wants an article in front of some country names, and Intl doesn't supply one:
// "works in Philippines" and "pays out in United States" are the giveaway. The rule covers
// the plurals and the unions rather than listing 249 countries, with a short list for the
// ones no rule catches. Only for English prose — every other language handles this its own
// way, and a label in a dropdown never takes an article.
// The two Congos are deliberately absent: Intl's English names for them are
// "Congo - Kinshasa" and "Congo - Brazzaville", which take no article.
const THE_ALWAYS = new Set(['PH', 'NL', 'BS', 'MV', 'GM', 'KM', 'SC', 'IM', 'VA']);
function theName(name, c) {
  if (THE_ALWAYS.has(c) || /(Islands|Isles)$/.test(name) || /^United /.test(name) || / Republic$/.test(name)) return `the ${name}`;
  return name;
}
export function countryName(c, forLang) {
  const dn = displayNames('region', forLang);
  let n = null;
  try { n = dn && dn.of(c); } catch {}
  const name = n && n !== c ? n : (COUNTRIES[c]?.n || c);
  // The article belongs to prose, so only when this is the prose language and it's English.
  return !forLang && lang() === 'en' ? theName(name, c) : name;
}
function currencyName(code) {
  const dn = displayNames('currency');
  let n = null;
  try { n = dn && dn.of(code); } catch {}
  return n && n !== code ? n : code;
}
function joinList(items) {
  try { return new Intl.ListFormat(lang(), { type: 'conjunction' }).format(items); } catch { return items.join(', '); }
}
// Rail ids (pix, sepa, fps…) to words. An id with no key prints as itself rather than as
// a raw "gm.geo.rail.x", so a new rail in the data can never leak a key onto the page.
function railNames(ids) {
  return joinList((ids || []).map(id => { const k = `gm.geo.rail.${id}`; const s = t(k); return s === k ? id : s; }));
}
function fmtDate(iso) {
  try { return new Date(`${iso}T12:00:00Z`).toLocaleDateString(lang(), { day: 'numeric', month: 'long', year: 'numeric' }); } catch { return iso; }
}
function placeName(c, s) {
  return c === 'US' && s && US_STATES[s] ? US_STATES[s].n : countryName(c);
}

